// Converts the single-file Runo site sources (../src) into content this Next.js app renders.
//   node scripts/import-runo.mjs [path-to-runo-site-src]
// Output (committed, so the app builds without the original sources):
//   content/pages/<id>.html     page markup with its scoped <style>
//   content/scripts/<id>.js     the page's behaviour as an ES module
//   content/scripts/index.js    lazy-import map
//   content/sprite.html         shared SVG sprite (logo mark + icons)
//   app/globals.css             the shared design system
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(process.argv[2] || join(app, '..', 'src'));
const out = (f, s) => { mkdirSync(dirname(join(app, f)), { recursive: true }); writeFileSync(join(app, f), s); };

// "#/dashboard" (hash router)  ->  "/dashboard" (real routes)
const routes = (s) => s.replace(/(["'`])#\//g, '$1/');

const ids = readdirSync(join(src, 'pages')).filter((f) => f.endsWith('.html')).map((f) => f.slice(0, -5)).sort();
for (const id of ids) {
  const raw = readFileSync(join(src, 'pages', `${id}.html`), 'utf8');
  let js = '';
  let html = raw.replace(/<script\b[^>]*>([\s\S]*?)<\/script>/gi, (_, body) => { js += body.trim() + '\n'; return ''; }).trim();
  html = routes(html).replace(/<section class="page"/, '<section class="page is-active"');
  if (!html.includes(`id="p-${id}"`)) throw new Error(`${id}: no <section id="p-${id}">`);
  js = routes(js)
    .replace(/\bwindow\.addEventListener\(/g, 'env.on(window, ')
    .replace(/\bdocument\.addEventListener\(/g, 'env.on(document, ');
  out(`content/pages/${id}.html`, html + '\n');
  out(`content/scripts/${id}.js`, `/* Generated from src/pages/${id}.html by scripts/import-runo.mjs. Edit the source, then re-import. */
/* eslint-disable */
export default function register(Runo, env) {
  // Timers and listeners come from env so they are cleaned up when the page unmounts.
  const { setTimeout, setInterval, requestAnimationFrame, addEventListener } = env;
${js.split('\n').map((l) => (l ? '  ' + l : l)).join('\n')}}
`);
}
out('content/scripts/index.js', `/* Generated by scripts/import-runo.mjs. One lazily loaded behaviour module per page. */
const scripts = {
${ids.map((id) => `  '${id}': () => import('./${id}.js'),`).join('\n')}
};
export default scripts;
`);

const shell = readFileSync(join(src, 'shell.html'), 'utf8');
const sprite = shell.match(/<svg width="0"[\s\S]*?<\/svg>/);
if (!sprite) throw new Error('sprite not found in shell.html');
out('content/sprite.html', sprite[0] + '\n');

const css = readFileSync(join(src, 'base.css'), 'utf8');
out('app/globals.css', `/* Generated from src/base.css by scripts/import-runo.mjs. */
${css}
/* Next.js: Geist is loaded with next/font and exposed as --font-geist (see app/layout.jsx). */
:root{--font:"Aeonik",var(--font-geist),"Geist","Helvetica Neue",Arial,sans-serif}
`);

console.log(`Imported ${ids.length} pages: ${ids.join(', ')}`);
